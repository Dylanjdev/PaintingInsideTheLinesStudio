import fs from 'node:fs';

const appSource = fs.readFileSync('src/App.jsx', 'utf8');
const tachyonsSource = fs.readFileSync('node_modules/tachyons/css/tachyons.min.css', 'utf8');
const usedClassNames = new Set();

for (const match of appSource.matchAll(/["'`]([^"'`{};<>]+)["'`]/g)) {
  for (const token of match[1].split(/\s+/)) {
    const className = token.trim();

    if (/^[a-z0-9_-]+(?:-[a-z0-9]+)*$/i.test(className)) {
      usedClassNames.add(className);
    }
  }
}

const escapeClassName = (className) => className.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
const classPatterns = [...usedClassNames].map(
  (className) => new RegExp(`\\.${escapeClassName(className)}(?=[\\s,.#:{>+~\\[]|$)`)
);

function ruleMatches(selector) {
  return classPatterns.some((pattern) => pattern.test(selector));
}

function filterRules(source) {
  let output = '';
  let index = 0;

  while (index < source.length) {
    const openBrace = source.indexOf('{', index);

    if (openBrace === -1) {
      break;
    }

    const selector = source.slice(index, openBrace).trim();
    let depth = 1;
    let end = openBrace + 1;

    while (end < source.length && depth > 0) {
      if (source[end] === '{') {
        depth += 1;
      } else if (source[end] === '}') {
        depth -= 1;
      }

      end += 1;
    }

    const body = source.slice(openBrace + 1, end - 1);

    if (selector.startsWith('@media')) {
      const filteredBody = filterRules(body);

      if (filteredBody) {
        output += `${selector}{${filteredBody}}`;
      }
    } else if (selector.startsWith('@')) {
      output += `${selector}{${body}}`;
    } else if (ruleMatches(selector)) {
      output += `${selector}{${body}}`;
    }

    index = end;
  }

  return output;
}

const usedCss = filterRules(tachyonsSource);

fs.writeFileSync(
  'src/tachyons-used.css',
  `/* Generated by scripts/build-tachyons-used.mjs from Tachyons utilities used in src/App.jsx. */\n${usedCss}\n`
);
